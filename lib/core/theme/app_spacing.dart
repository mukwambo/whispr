/// Named spacing scale, replacing the magic numbers (10 / 20 / 30 / 50)
/// that were hand-rolled as SizedBox heights/widths across every page.
class AppSpacing {
  const AppSpacing._();

  static const xxs = 6.0;
  static const xs = 10.0;
  static const sm = 20.0;
  static const md = 30.0;
  static const lg = 40.0;
  static const xl = 50.0;
  static const xxl = 100.0;
}
